"""Bounded synthetic-only ASGI observations; no browser-delivery claims."""

LIMIT = 1_000_000
ROUTES = {
    ("GET", "/msx/start.json"): "start_config",
    ("GET", "/msx/remember.json"): "entry_content",
    ("GET", "/msx/remember.html"): "plugin_html",
    ("GET", "/msx/remember.js"): "plugin_script",
    ("POST", "/api/device-authorization/pair"): "authorization_pair",
    ("POST", "/api/device-authorization/renew"): "authorization_renew",
}
STATUSES = (200, 204, 400, 401, 403, 404, 405, 409, 413, 415, 429, 500, 502, 503, 504)


def category(scope):
    """Match whole route shapes; never retain their variable capability segment."""
    method, path = scope.get("method"), scope.get("path", "")
    fixed = ROUTES.get((method, path))
    if fixed is not None:
        return fixed
    parts = path.split("/")
    if (
        method == "GET"
        and len(parts) == 5
        and parts[:3] == ["", "msx", "device"]
        and parts[3]
        and parts[4] == "home.json"
    ):
        return "private_home"
    return None


def increment(values, key):
    values[key] = min(LIMIT, values[key] + 1)


class RememberObservations:
    """Aggregate fixed counters, scoped to one synthetic backend process.

    A final send returning is not browser receipt, parsing or authorization.
    Aborted means app/send raised (including cancellation), even after a final
    send. Incomplete means no final-body send returned, including normal return.
    No receive is consumed or wrapped, so disconnects are not inferred.
    """

    def __init__(self):
        self.counts = {
            name: {
                "received": 0,
                "response_start_send_returned": {**{str(s): 0 for s in STATUSES}, "other": 0},
                "final_body_send_returned": 0,
                "aborted": 0,
                "incomplete": 0,
            }
            for name in (*ROUTES.values(), "private_home")
        }

    def snapshot(self):
        return {
            name: {
                **values,
                "response_start_send_returned": dict(values["response_start_send_returned"]),
            }
            for name, values in self.counts.items()
        }


class RememberObservationMiddleware:
    """Transparent user middleware, inside Starlette's outer error handler.

    A 500 generated by ServerErrorMiddleware is outside this boundary. Original
    scope/receive/messages and raised exceptions pass through unchanged.
    """

    def __init__(self, app, *, observations):
        self.app = app
        self.observations = observations

    async def __call__(self, scope, receive, send):
        name = category(scope) if scope["type"] == "http" else None
        if name is None:
            await self.app(scope, receive, send)
            return
        values = self.observations.counts[name]
        increment(values, "received")
        started = final = returned = False

        async def observed_send(message):
            nonlocal started, final
            await send(message)
            if message["type"] == "http.response.start" and not started:
                started = True
                status = message.get("status")
                key = str(status) if type(status) is int and status in STATUSES else "other"
                increment(values["response_start_send_returned"], key)
            elif (
                message["type"] == "http.response.body"
                and not message.get("more_body", False)
                and not final
            ):
                final = True
                increment(values, "final_body_send_returned")

        try:
            await self.app(scope, receive, observed_send)
            returned = True
        finally:
            if not returned:
                increment(values, "aborted")
            if not final:
                increment(values, "incomplete")
